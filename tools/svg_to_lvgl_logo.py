#!/usr/bin/env python3
"""Generate the T-Deck LVGL images (TD-THEME-01).

Run: DYLD_FALLBACK_LIBRARY_PATH=/opt/homebrew/lib uv run --with cairosvg --with pillow tools/svg_to_lvgl_logo.py
     (macOS: cairosvg needs Homebrew's libcairo, which is not on uv's default library path)

  src/t-deck/mc_logo_img.c  MeshCom logo, 64x64, LV_IMG_CF_TRUE_COLOR_ALPHA (RGB565, byte-swapped
                            for LV_COLOR_16_SWAP=1, plus alpha byte), from the inline SVG of the web GUI
  src/t-deck/mc_lock_img.c  padlock glyph, 14x16, LV_IMG_CF_ALPHA_8BIT (recolour with img_recolor)

Deterministic: no timestamps, fixed render sizes.
"""
from __future__ import annotations

import io
import re
import sys
from pathlib import Path

import cairosvg
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
WEB_SRC = ROOT / "src" / "web_functions" / "web_functions.cpp"
OUT_DIR = ROOT / "src" / "t-deck"
LOGO_SIZE = 64
LOCK_W, LOCK_H = 14, 16
SS = 16  # supersampling for the procedural lock


def extract_svg(path: Path) -> str:
    """Concatenate the C string literals of the web_client.print/println calls that carry the logo SVG."""
    lines = path.read_text(encoding="utf-8").splitlines()
    start = next(i for i, ln in enumerate(lines) if 'id=\\"mc_logo\\"' in ln)
    parts: list[str] = []
    for ln in lines[start:]:
        m = re.search(r'web_client\.print(?:ln)?\("(.*)"\);', ln)
        if not m:
            raise SystemExit(f"unexpected line in logo block: {ln!r}")
        parts.append(m.group(1))
        if "</svg>" in ln:
            break
    svg = "".join(parts)
    # the version text is a compile-time macro; the glyph carries no version
    svg = svg.replace('" MESHCOM_VERSION_SHORT "', "")
    svg = svg.replace('\\"', '"').replace("\\n", "\n")
    if "MESHCOM_" in svg:
        raise SystemExit("unresolved macro left in SVG")
    return svg


def fmt_bytes(data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",")
    return "\n".join(rows)


def c_file(name: str, w: int, h: int, cf: str, data: bytes, px_expr: str, desc: str) -> str:
    return f"""// generated by tools/svg_to_lvgl_logo.py, do not edit
// {desc}
#if defined(BOARD_T_DECK) || defined(BOARD_T_DECK_PLUS)
#include <lvgl.h>

static const uint8_t {name}_map[] = {{
{fmt_bytes(data)}
}};

const lv_img_dsc_t {name} = {{
    .header.cf = {cf},
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {w},
    .header.h = {h},
    .data_size = {w * h} * {px_expr},
    .data = {name}_map,
}};
#endif
"""


def logo() -> str:
    png = cairosvg.svg2png(
        bytestring=extract_svg(WEB_SRC).encode("utf-8"),
        output_width=LOGO_SIZE,
        output_height=LOGO_SIZE,
    )
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    out = bytearray()
    raw = img.tobytes()
    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i : i + 4]
        c = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += bytes((c >> 8, c & 0xFF, a))  # LV_COLOR_16_SWAP=1: high byte first
    return c_file("mc_logo_img", LOGO_SIZE, LOGO_SIZE, "LV_IMG_CF_TRUE_COLOR_ALPHA", bytes(out),
                  "LV_IMG_PX_SIZE_ALPHA_BYTE",
                  "MeshCom logo from the web GUI SVG (web_functions.cpp), RGB565 swapped + alpha, version text omitted")


def lock() -> str:
    s = SS
    img = Image.new("L", (LOCK_W * s, LOCK_H * s), 0)
    d = ImageDraw.Draw(img)
    # shackle: ring of an arch over the body
    sx0, sx1 = 3.0, 11.0
    top, body_top = 1.0, 7.0
    d.ellipse([sx0 * s, top * s, sx1 * s, (top + (sx1 - sx0)) * s], fill=255)
    d.ellipse([(sx0 + 1.8) * s, (top + 1.8) * s, (sx1 - 1.8) * s, (top + (sx1 - sx0) - 1.8) * s], fill=0)
    d.rectangle([sx0 * s, (top + 4.0) * s, (sx0 + 1.8) * s, (body_top + 0.5) * s], fill=255)
    d.rectangle([(sx1 - 1.8) * s, (top + 4.0) * s, sx1 * s, (body_top + 0.5) * s], fill=255)
    # body
    d.rounded_rectangle([1.0 * s, body_top * s, 13.0 * s, 15.0 * s], radius=1.5 * s, fill=255)
    # keyhole
    d.ellipse([5.8 * s, 9.2 * s, 8.2 * s, 11.6 * s], fill=0)
    d.rectangle([6.4 * s, 10.8 * s, 7.6 * s, 13.3 * s], fill=0)
    small = img.resize((LOCK_W, LOCK_H), Image.BOX)  # area average: no ringing into the transparent area
    return c_file("mc_lock_img", LOCK_W, LOCK_H, "LV_IMG_CF_ALPHA_8BIT", small.tobytes(), "1",
                  "padlock glyph, alpha only (recolour with img_recolor)")


def main() -> int:
    (OUT_DIR / "mc_logo_img.c").write_text(logo(), encoding="utf-8")
    (OUT_DIR / "mc_lock_img.c").write_text(lock(), encoding="utf-8")
    print("wrote mc_logo_img.c, mc_lock_img.c")
    return 0


if __name__ == "__main__":
    sys.exit(main())
