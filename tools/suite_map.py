#!/usr/bin/env python3
"""Generated inventory of the Unity host suites (TESTGATE-01).

    python3 tools/suite_map.py --write    # regenerate docs/test-suite-inventory.md
    python3 tools/suite_map.py --check    # exit 1 when the committed file is stale (host gate)

The table is derived from the tree on every call: the native envs of platformio.ini, the
suites each env runs, the RUN_TEST count, the production files a suite compiles or includes
directly, whether it reads source files as text (a pin), and whether its envs run under the
address and undefined-behaviour sanitizers. Nothing in it is typed by hand, so it cannot go
stale without the gate noticing. The prose around it lives in docs/test-suite-map.md.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import regression_select as rs  # noqa: E402

OUT = rs.ROOT / "docs" / "test-suite-inventory.md"
RUN_TEST_RE = re.compile(r"^\s*RUN_TEST\s*\(", re.M)


def rows(project: rs.Project) -> list[tuple[str, int, str, str, str, str]]:
    """(suite, cases, envs, production files, pin, sanitizer) per suite, sorted by suite."""
    suite_envs: dict[str, list[str]] = {}
    for env in project.envs:
        for suite in project.env_suites(env):
            suite_envs.setdefault(suite, []).append(env)
    out = []
    for suite in sorted(suite_envs):
        envs = suite_envs[suite]
        sources = [
            f for f in project.files
            if f.startswith(f"test/{suite}/") and f.endswith(rs.SOURCE_SUFFIXES)
        ]
        cases = sum(len(RUN_TEST_RE.findall(project.text(f))) for f in sources)
        prod: set[str] = set()
        for env in envs:
            prod.update(f[4:] for f in project.env_src_files(env))
            search = [*project.env_include_dirs(env), "src"]
            for f in sources:
                for inc in rs.INCLUDE_RE.findall(project.text(f)):
                    prod.update(h[4:] for h in project.resolve(inc, f, search) if h.startswith("src/"))
        pin = "yes" if any(rs.FILE_READ_RE.search(project.text(f)) for f in sources) else ""
        sanitized = [e for e in envs if "-fsanitize" in project.opt(e, "build_flags")]
        san = "yes" if len(sanitized) == len(envs) else ("partly" if sanitized else "")
        shown = sorted(prod)
        prod_text = ", ".join(f"`{p}`" for p in shown[:6]) + (f" and {len(shown) - 6} more" if len(shown) > 6 else "")
        out.append((suite, cases, ", ".join(envs), prod_text or "none", pin, san))
    return out


def render(project: rs.Project) -> str:
    table = rows(project)
    total_cases = sum(r[1] for r in table)
    lines = [
        "# Unity suite inventory (generated)",
        "",
        "Generated by `tools/suite_map.py --write`. Do not edit by hand: the host gate runs",
        "`tools/suite_map.py --check` and fails when this file differs from the tree.",
        "",
        f"- Native test envs: {len(project.envs)}",
        f"- Suites: {len(table)}",
        f"- `RUN_TEST` cases: {total_cases} (a suite in two envs is counted once here; the gate counts it per env)",
        f"- Suites that read source files as text: {sum(1 for r in table if r[4])}",
        f"- Suites with every env under ASan/UBSan: {sum(1 for r in table if r[5] == 'yes')}",
        "",
        "Columns: **Production files** are the `src/` files the envs compile plus the `src/` headers the suite",
        "includes directly. **Reads source** marks a suite with at least one source-text check; such a case",
        "proves that a string is present, not that the code behaves.",
        "",
        "| Suite | Cases | Env(s) | Production files | Reads source | ASan/UBSan |",
        "| --- | ---: | --- | --- | --- | --- |",
    ]
    lines += [f"| {s} | {c} | {e} | {p} | {pin} | {san} |" for s, c, e, p, pin, san in table]
    return "\n".join(lines) + "\n"


def normalise(text: str) -> list[str]:
    """Table rows without the column padding a formatter adds."""
    return [re.sub(r"\s*\|\s*", "|", re.sub(r"-{3,}:?", "-", line)).strip() for line in text.splitlines() if line.strip()]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(rs.Project())
    if args.write:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(rs.ROOT)}")
        return 0
    have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if normalise(have) == normalise(text):
        print("suite inventory is current")
        return 0
    want, got = normalise(text), set(normalise(have))
    for line in [w for w in want if w not in got][:10]:
        print(f"stale or missing: {line}", file=sys.stderr)
    print("docs/test-suite-inventory.md is stale -- run: python3 tools/suite_map.py --write", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
