#!/usr/bin/env python3
"""Generate src/web_functions/web_assets.h: the GUI's static CSS/JS as gzip blobs.

    python3 tools/gen_web_assets.py          # rewrite the header
    python3 tools/gen_web_assets.py --check  # exit 1 when the header is out of date

Sources: src/web_functions/web/{mc.css,mc.js,mcau.js,mcrm.js}. Before compression every full-line comment
(`// ...` in .js, `/* ... */` in .css) and every blank line is dropped, so the sources can carry the comments
and the blobs stay small. The blob is gzip level 9 with mtime 0 and no file name. The ?v= tag of an asset is
the first 8 hex digits of the SHA-256 of the stripped text, so it does not depend on the zlib version.
Stdlib only.
"""

import argparse
import gzip
import hashlib
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "src" / "web_functions" / "web"
HEADER = ROOT / "src" / "web_functions" / "web_assets.h"

# (source file, C identifier stem, only ESP32)
ASSETS = (
    ("mc.css", "MC_CSS", False),
    ("mc.js", "MC_JS", False),
    ("mcau.js", "MC_AU_JS", True),
    ("mcrm.js", "MC_RM_JS", False),
)


def strip(name, text):
    """Drop full-line comments and blank lines."""
    out = []
    for line in text.splitlines():
        s = line.strip()
        if not s:
            continue
        if name.endswith(".js") and s.startswith("//"):
            continue
        if name.endswith(".css") and s.startswith("/*") and s.endswith("*/"):
            continue
        out.append(s if name.endswith(".css") else line.rstrip())
    return ("\n".join(out) + "\n").encode("utf-8")


def tag(raw):
    return hashlib.sha256(raw).hexdigest()[:8]


def render():
    parts = [
        "// GENERATED by tools/gen_web_assets.py from src/web_functions/web/*.{css,js} -- do not edit.\n"
        "// Regenerate: python3 tools/gen_web_assets.py   (check: python3 tools/gen_web_assets.py --check)\n"
        "// gzip -9, mtime 0; <ID>_TAG is the ?v= cache tag (hash of the comment-stripped source).\n"
        "// Included by web_functions.cpp ONLY: the arrays are static, a second user would get its own copy.\n"
        "#ifndef _WEB_ASSETS_H_\n#define _WEB_ASSETS_H_\n\n#include <stdint.h>\n"
    ]
    for fname, ident, esp_only in ASSETS:
        raw = strip(fname, (WEB / fname).read_text(encoding="utf-8"))
        gz = gzip.compress(raw, 9, mtime=0)
        body = []
        for i in range(0, len(gz), 16):
            body.append("    " + ",".join("0x%02x" % b for b in gz[i : i + 16]) + ",")
        blk = [
            "// %s: %d B raw, %d B gzip" % (fname, len(raw), len(gz)),
            '#define WEB_%s_TAG "%s"' % (ident, tag(raw)),
            "static const uint8_t web_%s_gz[] = {" % ident.lower(),
            *body,
            "};",
        ]
        if esp_only:
            blk = ["#if defined(ESP32)"] + blk + ["#endif"]
        parts.append("\n" + "\n".join(blk) + "\n")
    parts.append("\n#endif // _WEB_ASSETS_H_\n")
    return "".join(parts)


def decode_header(text):
    """{identifier: (tag, decompressed bytes)} of a generated header."""
    res = {}
    for m in re.finditer(
        r'#define WEB_(\w+)_TAG "(\w+)"\nstatic const uint8_t web_\w+_gz\[\] = \{(.*?)\};', text, re.S
    ):
        blob = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", m.group(3)))
        res[m.group(1)] = (m.group(2), zlib.decompress(blob, 31))
    return res


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when web_assets.h is out of date")
    args = ap.parse_args()
    new = render()
    if not args.check:
        HEADER.write_text(new, encoding="utf-8")
        return 0
    old = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
    # Compare the decoded content, not the bytes: another zlib may compress to different bytes.
    if decode_header(old) != decode_header(new):
        print("web_assets.h is out of date: python3 tools/gen_web_assets.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
