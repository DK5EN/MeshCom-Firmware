#!/usr/bin/env python3
"""
remote_cmd.py - build and verify RM1 remote-management command DMs (issue #1189).

Reference implementation of the wire format in
docs/concept-open-issues-20261004.md section 6.2. The firmware C++ host test
loads tools/tests/remote_cmd_vectors.json (generated by this file) and must
reproduce every tag.

Wire format:
    command  RM1 <ctr> <cmd>[ <args>] <tag>
    reply    RM1 <ctr> ok <status> <tag>   |   RM1 <ctr> err <reason> <tag>

    K         = SHA-256(passwd with trailing spaces stripped)            32 bytes
    canonical = "RM1|" + dst + "|" + src + "|" + ctr + "|" + cmd[ + " " + args]
    tag       = first 8 bytes of HMAC-SHA256(K, canonical), 16 lower-case hex
    reply tag = same over "RM1R|" + dst + "|" + src + "|" + ctr + "|" + result
                (dst = managed node, src = sender, as in the command)

Usage:
    remote_cmd.py --dst DK5EN-90 --src DK5EN-1 --passwd SECRET --ctr 42 reboot
    remote_cmd.py --dst DK5EN-90 --src DK5EN-1 --passwd SECRET --ctr 43 txpower 2
    remote_cmd.py --dst DK5EN-90 --src DK5EN-1 --passwd SECRET sync
    remote_cmd.py --dst DK5EN-90 --src DK5EN-1 --passwd SECRET --verify "RM1 42 ok rebooting <tag>"

Default is print-only. With --send-host <ip> the DM text is sent through the net
console (TCP 2323) of the SENDER node, as the direct message
`::{<DST>}<dm text>` (the console's user-message form; see
tools/bench/tdeck_harness.py). Never a group, never a broadcast.

Requires: Python 3.8+, stdlib only.
"""

from __future__ import annotations

import argparse
import hashlib
import hmac
import json
import os
import re
import socket
import sys
import time
from typing import Any, Dict, List, Optional

PROTO = "RM1"
CTR_MAX = 0xFFFFFFFF
PASSWD_MAX = 14  # node_passwd is char[15]
ARGS_MAX = 39  # RM_MAX_ARGS in src/remote_cmd.h (RmCmd::args[40])
RESULT_MAX = 108  # RM_MAX_RESULT: "RM1 <10> <108> <16>" is 140 chars, the DM limit
LEGACY_RESULT_MAX = 63  # replies of the first 13 commands stay within this (version skew)
CAP_LEVEL = 2  # "rm=<n>" token of the sync reply
TAG_HEX_LEN = 16  # 8 bytes

# cmd -> argument shape. None = no args, tuple = fixed set of allowed arg strings,
# "int" = single unsigned decimal, "out" = "<a0..a7|b0..b7> <on|off>"
# (MCP23017 pin, the firmware's `--setout` form).
ALLOWLIST: Dict[str, Any] = {
    "reboot": None,
    "status": None,
    "sendpos": None,
    "sendtrack": None,
    "gps": ("on", "off"),
    "track": ("on", "off"),
    "display": ("on", "off"),
    "led": ("on", "off"),
    "gateway": ("on", "off"),
    "mesh": ("on", "off"),
    "txpower": "int",
    "setout": "out",
    "sync": None,
    # extended commands (RM ext W2-A): syntax only, ranges and the strict charset are the
    # executor's job (err range / err text). Capitals are allowed in the args of these shapes only.
    "radio": None,
    "sens": None,
    "txq": None,
    "mbox": None,
    "maxhop": None,
    "name": "name",  # none (read) | free text 1..19 (write)
    "atxt": "atxt",  # none (read) | free text 1..39 (write)
    "pos": "pos",    # none (read) | "<lat> <lon> <alt>" (write)
    "mh": "mh",      # row index 0..999 | callsign with optional SSID
}

# Hard-blocked whatever the tag (6.4). Checked before the allowlist so the
# refusal names the reason.
BLOCKED_CMDS = frozenset(
    {
        "cleanflash", "ota-update", "dfu", "deepsleep", "setcall", "passwd",
        "webpwd", "btcode", "setssid", "setpwd", "wifiset", "updrepo",
        "updchan", "autoupdate", "rm", "remotemgmt", "stor", "rmstrictsecurity",
    }
)
BLOCKED_CHARS = ("--", ";", "{", "%")

_INT_RE = re.compile(r"^(0|[1-9][0-9]{0,2})$")
_OUT_RE = re.compile(r"[ab][0-7] (on|off)")
_CALL_RE = re.compile(r"^[A-Z0-9/]{2,12}(-[0-9]{1,2})?$")   # upper case: the node binds its configured call
_SEND_CALL_RE = re.compile(r"^[A-Z0-9/]{2,12}-[0-9]{1,2}$")
_ROW_RE = re.compile(r"[0-9]{1,3}")
_COORD = r"-?[0-9]{1,3}(\.[0-9]{1,6})?"
_POS_RE = re.compile(_COORD + " " + _COORD + " [0-9]{1,5}")
_MHCALL_RE = re.compile(r"[A-Z0-9]{3,9}|[A-Z0-9]{2,8}-[0-9]{1,2}")  # 3..9 chars total, either case on the wire
_TEXT_BAD = set("{}|:")  # wire-level: '|' is the canonical separator
_TAG_RE = re.compile(r"^[0-9a-f]{16}$")


class RmError(ValueError):
    """A command or reply was refused (allowlist, range or format)."""


# ---------------------------------------------------------------------------
# crypto
# ---------------------------------------------------------------------------

def hmac_sha256(key: bytes, msg: bytes) -> bytes:
    """HMAC-SHA256 (RFC 2104); the one primitive every tag goes through."""
    return hmac.new(key, msg, hashlib.sha256).digest()


def derive_key(passwd: str) -> bytes:
    """K = SHA-256(passwd with trailing spaces stripped), 32 bytes."""
    p = passwd.rstrip(" ")
    if not p:
        raise RmError("empty passwd")
    raw = p.encode("utf-8")
    if len(passwd.rstrip(" ")) > PASSWD_MAX:
        raise RmError("passwd longer than %d characters" % PASSWD_MAX)
    return hashlib.sha256(raw).digest()


def tag(key: bytes, canonical_text: str) -> str:
    """First 8 bytes of HMAC-SHA256(key, canonical_text) as 16 lower-case hex chars."""
    return hmac_sha256(key, canonical_text.encode("utf-8")).hex()[:TAG_HEX_LEN]


# ---------------------------------------------------------------------------
# validation
# ---------------------------------------------------------------------------

def _check_call(name: str, call: str) -> None:
    if not isinstance(call, str) or not _CALL_RE.fullmatch(call):
        raise RmError("bad %s call %r" % (name, call))


def _check_ctr(ctr: int) -> None:
    if isinstance(ctr, bool) or not isinstance(ctr, int):
        raise RmError("ctr must be an integer")
    if ctr < 0 or ctr > CTR_MAX:
        raise RmError("ctr out of range 0..%d" % CTR_MAX)


_MIXED_CASE_SHAPES = ("name", "atxt", "pos", "mh")


def _check_ext_args(cmd: str, shape: str, args: str) -> None:
    """Syntax of the extended shapes (mirrors argsMatch in src/remote_cmd.cpp)."""
    if shape in ("name", "atxt", "pos") and args == "":
        return  # read form
    if shape in ("name", "atxt"):
        limit = 19 if shape == "name" else 39
        if not 1 <= len(args) <= limit or any(c in _TEXT_BAD for c in args):
            raise RmError("%s needs free text of 1..%d characters without { } | :" % (cmd, limit))
    elif shape == "pos":
        if not _POS_RE.fullmatch(args):
            raise RmError("pos needs '<lat> <lon> <alt>'")
    elif args.isdigit():  # an all-digit token is a row index only
        if not _ROW_RE.fullmatch(args):
            raise RmError("mh row index is 0..999")
    elif not (len(args) <= 9 and _MHCALL_RE.fullmatch(args.upper())):
        raise RmError("mh needs a row index 0..999 or a callsign")


def validate_command(cmd: str, args: str, ctr: int) -> None:
    """Raise RmError unless (cmd, args, ctr) is an allowlisted RM1 command."""
    _check_ctr(ctr)
    if not isinstance(cmd, str) or not isinstance(args, str):
        raise RmError("cmd and args must be strings")
    text = cmd + (" " + args if args else "")
    for bad in BLOCKED_CHARS:
        if bad in text:
            raise RmError("blocked sequence %r" % bad)
    if len(args) > ARGS_MAX:
        raise RmError("args longer than %d characters" % ARGS_MAX)
    if cmd in BLOCKED_CMDS:
        raise RmError("command %r is hard-blocked" % cmd)
    if not text.isascii() or not text.isprintable():
        raise RmError("non-printable or non-ASCII text")
    if cmd != cmd.lower():
        raise RmError("cmd must be lower case")
    # args stay lower case except where a shape allows capitals (free text, callsign); nothing is case-folded
    if args != args.lower() and ALLOWLIST.get(cmd) not in _MIXED_CASE_SHAPES:
        raise RmError("args must be lower case")
    if "  " in text or text != text.strip():
        raise RmError("single spaces only, no leading/trailing space")
    if cmd not in ALLOWLIST:
        raise RmError("command %r not on the allowlist" % cmd)

    shape = ALLOWLIST[cmd]
    if shape is None:
        if args:
            raise RmError("%s takes no arguments" % cmd)
    elif shape == "int":
        if not _INT_RE.fullmatch(args):
            raise RmError("%s needs one unsigned integer (0..999)" % cmd)
    elif shape == "out":
        if not _OUT_RE.fullmatch(args):
            raise RmError("setout needs '<a0..a7|b0..b7> <on|off>'")
    elif shape in _MIXED_CASE_SHAPES:
        _check_ext_args(cmd, shape, args)
    elif args not in shape:
        raise RmError("%s needs one of %s" % (cmd, "|".join(shape)))

    if cmd == "sync":
        if ctr != 0:
            raise RmError("sync uses ctr 0")
    elif ctr < 1:
        raise RmError("ctr 0 is reserved for sync")


# ---------------------------------------------------------------------------
# command
# ---------------------------------------------------------------------------

def canonical(dst: str, src: str, ctr: int, cmd: str, args: str = "") -> str:
    """Canonical string a command tag is computed over."""
    return "%s|%s|%s|%d|%s%s" % (PROTO, dst, src, ctr, cmd, " " + args if args else "")


def build_command(
    dst: str, src: str, ctr: int, cmd: str, args: str, passwd: str
) -> str:
    """Return the DM text `RM1 <ctr> <cmd>[ <args>] <tag>`; refuse anything off-list."""
    _check_call("dst", dst)
    _check_call("src", src)
    validate_command(cmd, args, ctr)
    key = derive_key(passwd)
    t = tag(key, canonical(dst, src, ctr, cmd, args))
    return "%s %d %s%s %s" % (PROTO, ctr, cmd, " " + args if args else "", t)


# ---------------------------------------------------------------------------
# reply
# ---------------------------------------------------------------------------

def reply_canonical(dst: str, src: str, ctr: int, result: str) -> str:
    """Canonical string a reply tag is computed over (dst = managed node)."""
    return "%sR|%s|%s|%d|%s" % (PROTO, dst, src, ctr, result)


def build_reply(dst: str, src: str, ctr: int, result: str, passwd: str) -> str:
    """Reply DM text as the managed node sends it (used for vectors and tests)."""
    if not (result.startswith("ok ") or result.startswith("err ")):
        raise RmError("result must start with 'ok ' or 'err '")
    if len(result) > RESULT_MAX:
        raise RmError("result longer than %d characters" % RESULT_MAX)
    t = tag(derive_key(passwd), reply_canonical(dst, src, ctr, result))
    return "%s %d %s %s" % (PROTO, ctr, result, t)


def verify_reply(
    text: str, dst: str, src: str, passwd: str, ctr: Optional[int] = None
) -> Optional[Dict[str, Any]]:
    """Verify a reply DM from the managed node `dst` to the sender `src`.

    Returns {"ctr", "status" ("ok"|"err"), "text" (status/reason), "result"}
    when the tag matches (and `ctr` equals the expected counter, if given),
    otherwise None.
    """
    if not isinstance(text, str):
        return None
    parts = text.strip().split(" ")
    if len(parts) < 4 or parts[0] != PROTO or parts[2] not in ("ok", "err"):
        return None
    if not re.fullmatch(r"0|[1-9][0-9]{0,9}", parts[1]):
        return None
    got_ctr = int(parts[1])
    if got_ctr > CTR_MAX or (ctr is not None and got_ctr != ctr):
        return None
    got_tag = parts[-1]
    if not _TAG_RE.fullmatch(got_tag):
        return None
    result = " ".join(parts[2:-1])
    try:
        key = derive_key(passwd)
    except RmError:
        return None
    want = tag(key, reply_canonical(dst, src, got_ctr, result))
    if not hmac.compare_digest(want, got_tag):
        return None
    return {
        "ctr": got_ctr,
        "status": parts[2],
        "text": " ".join(parts[3:-1]),
        "result": result,
    }


