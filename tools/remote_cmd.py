def _status_expect(result: str) -> Optional[Dict[str, Any]]:
    """Fields the firmware's rmStatusParse() must produce (from the format itself)."""
    m = re.search(r" s=([A-Za-z]{5,6}) p=(\d+)/(\d+)( led=[01])?$", result)
    if not result.startswith("ok v=") or m is None:
        return None
    letters = m.group(1)
    sw = [(1 if ch.isupper() else 0) for ch in letters] + [-1] * (6 - len(letters))
    # flat scalars (the native test's JSON reader has no nesting); sw: gps,track,display,mesh,gateway,led
    return {"status_sw": ",".join(("-" if v < 0 else str(v)) for v in sw),
            "status_p": "%s/%s" % (m.group(2), m.group(3)),
            "status_led": len(letters) == 6 or m.group(4) is not None}


def generate_vectors() -> Dict[str, Any]:
    cmds: List[Dict[str, Any]] = []
    for passwd, dst, src, ctr, cmd, args in _VECTOR_CMDS:
        canon = canonical(dst, src, ctr, cmd, args)
        dm = build_command(dst, src, ctr, cmd, args, passwd)
        cmds.append(
            {
                "passwd": passwd,
                "dst": dst,
                "src": src,
                "ctr": ctr,
                "cmd": cmd,
                "args": args,
                "canonical": canon,
                "key_hex": derive_key(passwd).hex(),
                "tag": dm.rsplit(" ", 1)[1],
                "dm_text": dm,
            }
        )
    replies: List[Dict[str, Any]] = []
    for passwd, dst, src, ctr, result in _VECTOR_REPLIES:
        text = build_reply(dst, src, ctr, result, passwd)
        extra: Dict[str, Any] = {}
        st = _status_expect(result)
        if st is not None:
            extra.update(st)
        if result.startswith("ok ctr=") and " rm=" in result:
            extra["cap"] = CAP_LEVEL
        replies.append(
            {**extra,
                "passwd": passwd,
                "dst": dst,
                "src": src,
                "ctr": ctr,
                "result": result,
                "key_hex": derive_key(passwd).hex(),
                "reply_canonical": reply_canonical(dst, src, ctr, result),
                "reply_tag": text.rsplit(" ", 1)[1],
                "reply_text": text,
            }
        )
    return {
        "_note": "Generated by tools/remote_cmd.py --gen-vectors; do not edit by hand.",
        "proto": PROTO,
        "commands": cmds,
        "replies": replies,
    }


# ---------------------------------------------------------------------------
# net console send (sender node, TCP 2323, HMAC login like hmac_connect.py)
# ---------------------------------------------------------------------------

def send_via_console(
    host: str, dst: str, dm_text: str, console_passwd: str, port: int = 2323,
    listen_s: float = 3.0,
) -> str:
    """Send `dm_text` as a DM to `dst` through the net console of `host`.

    Uses the console's user-message form `::{CALL}text`. Returns the console
    output seen for `listen_s` seconds after the send.
    """
    if not _SEND_CALL_RE.fullmatch(dst):
        raise RmError("refusing to send: dst %r is not a call with SSID" % dst)
    if "\n" in dm_text or "\r" in dm_text:
        raise RmError("refusing to send: line break in text")
    s = socket.create_connection((host, port), timeout=10)
    try:
        s.settimeout(5)
        f = s.makefile("r", newline="\n")
        line = f.readline().strip()
        if console_passwd:
            if not line.upper().startswith("NONCE:"):
                raise RmError("unexpected console greeting %r" % line)
            nonce = bytes.fromhex(line.split()[1].strip())
            resp = hmac_sha256(console_passwd.encode(), nonce).hex()
            s.sendall((resp + "\n").encode())
            if f.readline().strip() != "OK":
                raise RmError("console authentication failed")
        out: List[str] = []
        # drain banner
        s.settimeout(1.0)
        try:
            while f.readline():
                pass
        except socket.timeout:
            pass
        s.sendall(("::{%s}%s\r\n" % (dst, dm_text)).encode())
        end = time.monotonic() + listen_s
        s.settimeout(0.5)
        while time.monotonic() < end:
            try:
                data = s.recv(512)
            except socket.timeout:
                continue
            if not data:
                break
            out.append(data.decode(errors="replace"))
        return "".join(out)
    finally:
        s.close()


