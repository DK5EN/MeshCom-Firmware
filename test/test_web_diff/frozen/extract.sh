#!/bin/sh
# Regenerates web_request_frozen.cpp and url_decode_frozen.cpp byte for byte from the pinned blobs
# (FORMAL-02, web server wave A step 0). Only the line ranges below and the entry-point renames; nothing
# else of the production files is copied. Usage: sh test/test_web_diff/frozen/extract.sh   (from the repo root)
# Then: shasum -a 256 -c test/test_web_diff/frozen/SHA256SUMS
set -eu
REF=3b1ce88fc548e1cac6708634623d902ead3263c1
D=test/test_web_diff/frozen
WF=$(mktemp); RH=$(mktemp); UD=$(mktemp)
trap 'rm -f "$WF" "$RH" "$UD"' EXIT
git show "$REF:src/web_functions/web_functions.cpp" >"$WF"
git show "$REF:src/web_functions/web_rm_handlers.cpp" >"$RH"
git show "$REF:src/url_decode.cpp" >"$UD"

# renames: function definitions and calls only (a name followed by "("), never the "/setparam/" strings
REN='s/(^|[^A-Za-z0-9_])work_webpage\(/\1work_webpage_frozen(/g
s/(^|[^A-Za-z0-9_])decodeURLPercentCoding\(/\1decodeURLPercentCoding_frozen(/g
s/(^|[^A-Za-z0-9_])call_function\(/\1call_function_frozen(/g
s/(^|[^A-Za-z0-9_])setparam\(/\1setparam_frozen(/g
s/(^|[^A-Za-z0-9_])getparam\(/\1getparam_frozen(/g
s/(^|[^A-Za-z0-9_])send_message\(/\1send_message_frozen(/g
s/(^|[^A-Za-z0-9_])web_read_body\(/\1web_read_body_frozen(/g
s/(^|[^A-Za-z0-9_])rmReadBody\(/\1rmReadBody_frozen(/g
s/(^|[^A-Za-z0-9_])send_http_header\(/\1send_http_header_frozen(/g
s/(^|[^A-Za-z0-9_])deliver_web_asset\(/\1deliver_web_asset_frozen(/g
s/(^|[^A-Za-z0-9_])url_percent_decode\(/\1url_percent_decode_frozen(/g'

seg() { # file first last label
    printf '\n// ==== %s lines %s-%s (blob %s) ====\n' "$4" "$2" "$3" "$(git rev-parse "$REF:$5")"
    sed -n "$2,$3p" "$1" | sed -E "$REN"
}

{
    printf '%s\n' '// FROZEN copy of the request path of the production web server (FORMAL-02, web server wave A step 0).'
    printf '%s\n' '// GENERATED by test/test_web_diff/frozen/extract.sh from git blobs at the commit pinned in that script.'
    printf '%s\n' '// Do not edit: the line ranges below are verbatim, the only change is the entry-point rename (*_frozen).'
    printf '%s\n' '// Everything outside the marked ranges is this file'"'"'s own plumbing (includes, namespace, forward declarations).'
    cat <<'PRE'
#include "../rig/web_rig.h"

#include <stdlib.h>
#include <string.h>
#include <vector>

#include <ArduinoJson.h>

#include <web_functions.h>
#include <web_setup.h>
#include <web_nodefunctioncalls.h>
#include <web_guard.h>
#include <web_auth.h>
#include <web_rm_util.h>
#include <web_rm_parse.h>   // RM_FORM_BODY_MAX
#include <backpressure.h>   // MsgOrigin, BP_SEND_*
#include <charset_filter.h> // charset_utf8_safe_truncate (live; not part of the refactor)
#include <fw_update.h>      // fwWebAdmit (live, header-only)
#include <web_txbuf.h>      // webTxBeginChunked declaration

void setMsgOrigin(MsgOrigin o); // loop_functions_extern.h in the original (recording stub: rig/web_stubs.cpp)

// the request path was written for the ESP32 build (AU gate, /austatus, /mcau.js): switch it on only now,
// after the real headers above (hmac_sha256.h would pull mbedtls in with ESP32 defined)
#define ESP32 1

namespace web_frozen
{
// own plumbing: forward declarations the verbatim ranges need before their definitions (web_functions.h has them in the original)
void send_http_header_frozen(uint16_t http_status_code, uint8_t content_type, const char *extra_header = nullptr);
size_t url_percent_decode_frozen(char *buf, size_t len);
void call_function_frozen(String web_header);
void send_message_frozen(String web_header);
void setparam_frozen(String web_header);
void getparam_frozen(String web_header);
PRE
    seg "$WF" 73 75 "web_functions.cpp" src/web_functions/web_functions.cpp
    seg "$WF" 228 233 "web_functions.cpp" src/web_functions/web_functions.cpp
    seg "$WF" 570 657 "web_functions.cpp (config buffer + web_read_body)" src/web_functions/web_functions.cpp
    seg "$RH" 39 40 "web_rm_handlers.cpp (body deadlines)" src/web_functions/web_rm_handlers.cpp
    seg "$RH" 44 70 "web_rm_handlers.cpp (rmReadBody)" src/web_functions/web_rm_handlers.cpp
    cat <<'MID'

// own plumbing: the recording stubs of the handlers (shared with the live wiring), bound to this unit's readers
#define WEB_RIG_RM_READ rmReadBody_frozen
#define WEB_RIG_READ_BODY web_read_body_frozen
#define WEB_RIG_CFG_ALLOC web_cfg_alloc
#define WEB_RIG_CFG_FREE web_cfg_free
#define WEB_RIG_CFG_BUF web_cfg_buf
#include "../stubs/web_handler_stubs.h"
MID
    seg "$WF" 954 1003 "web_functions.cpp (deliver_web_asset)" src/web_functions/web_functions.cpp
    seg "$WF" 1039 1542 "web_functions.cpp (work_webpage)" src/web_functions/web_functions.cpp
    seg "$WF" 1544 1554 "web_functions.cpp (decodeURLPercentCoding)" src/web_functions/web_functions.cpp
    seg "$WF" 4709 4763 "web_functions.cpp (send_http_header)" src/web_functions/web_functions.cpp
    seg "$WF" 4867 4949 "web_functions.cpp (send_message)" src/web_functions/web_functions.cpp
    seg "$WF" 5023 5273 "web_functions.cpp (call_function, setparam, getparam)" src/web_functions/web_functions.cpp
    printf '\n} // namespace web_frozen\n'
} >"$D/web_request_frozen.cpp"

{
    printf '%s\n' '// FROZEN copy of src/url_decode.cpp (the percent decoder the request path calls), FORMAL-02 web diff.'
    printf '%s\n' '// GENERATED by extract.sh; whole file, the only change is the rename url_percent_decode -> url_percent_decode_frozen.'
    printf '%s\n' '// The decoder steps of the migration (docs/web-server-seams-20261127.md steps 1-2) change src/url_decode.*;'
    printf '%s\n' '// this copy keeps the reference behaviour, so the differential sees such a change.'
    printf '%s\n' '#include <stddef.h>'
    printf '%s\n' 'namespace web_frozen'
    printf '%s\n' '{'
    sed -E "$REN" "$UD" | sed -e '1d'
    printf '%s\n' '} // namespace web_frozen'
} >"$D/url_decode_frozen.cpp"
